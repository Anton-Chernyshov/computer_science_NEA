package org.anton.nea.helpers;

import javafx.scene.paint.Color;

/**I LOVE HELPER CLASSESS WOOOOOOO!!!!
 * <p>Parses two colors as one object, makes it a *bit* easier for me</p>
 */
public class Color2 {
    public Color ColorA, ColorB;
    /**
     * @param colorA "primary" color
     * @param colorB "secondary" color
     */
    public Color2(final Color colorA, final Color colorB) {
        this.ColorA = colorA;
        this.ColorB = colorB;
    }
}
